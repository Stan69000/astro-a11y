import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import {
  resolveRoutesFromAssets,
  selectPrerenderedPages
} from '../packages/astro-integration/src/routes.js';

const rootDir = path.resolve('/tmp/site/dist');
const fileUrl = (rel) => pathToFileURL(path.join(rootDir, rel));

// Shape of IntegrationResolvedRoute: dynamic routes have no `pathname`.
const resolvedRoutes = [
  { pattern: '/', pathname: '/', type: 'page', isPrerendered: true },
  { pattern: '/blog/[slug]', pathname: undefined, type: 'page', isPrerendered: true },
  { pattern: '/rss.xml', pathname: '/rss.xml', type: 'endpoint', isPrerendered: true },
  { pattern: '/old', pathname: '/old', type: 'redirect', isPrerendered: true },
  { pattern: '/account', pathname: '/account', type: 'page', isPrerendered: false }
];

test('keeps only prerendered pages', () => {
  const pages = selectPrerenderedPages(resolvedRoutes);
  assert.deepEqual(
    pages.map((page) => page.pattern),
    ['/', '/blog/[slug]']
  );
});

test('resolves every file generated by dynamic routes without crashing', () => {
  const assets = new Map([
    ['/', [fileUrl('index.html')]],
    ['/blog/[slug]', [fileUrl('blog/hello/index.html'), fileUrl('blog/world/index.html')]],
    ['/rss.xml', [fileUrl('rss.xml')]]
  ]);
  const routes = resolveRoutesFromAssets(selectPrerenderedPages(resolvedRoutes), assets, rootDir);
  assert.deepEqual(routes, ['/', '/blog/hello/', '/blog/world/']);
});

test('supports build.format "file" output', () => {
  const pages = [{ pattern: '/about', type: 'page', isPrerendered: true }];
  const assets = new Map([['/about', [fileUrl('about.html')]]]);
  assert.deepEqual(resolveRoutesFromAssets(pages, assets, rootDir), ['/about.html']);
});

test('ignores files outside the output directory', () => {
  const pages = [{ pattern: '/', type: 'page', isPrerendered: true }];
  const assets = new Map([['/', [pathToFileURL(path.resolve('/tmp/elsewhere/index.html'))]]]);
  assert.deepEqual(resolveRoutesFromAssets(pages, assets, rootDir), []);
});

test('returns an empty list when Astro provides no assets map', () => {
  assert.deepEqual(resolveRoutesFromAssets(resolvedRoutes, undefined, rootDir), []);
});
